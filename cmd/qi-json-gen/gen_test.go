// writePkg writes a single Go source file into a temp dir and returns the dir.
func writePkg(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "input.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestGenerateScalars(t *testing.T) {
	dir := writePkg(t, `package example

type Config struct {
	Name string
	Port int64 `+"`json:\"port\"`"+`
}
`)
	got, err := generate(dir, []string{"Config"})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	src := string(got)
	want := []string{
		"// Code generated by qi-json-gen; DO NOT EDIT.",
		"package example",
		`"qi-json/marshal"`,
		"var configSchema = marshal.Struct[Config](",
		`marshal.String[Config]("Name", func(v *Config) *string { return &v.Name })`,
		`marshal.Int[Config]("port", func(v *Config) *int64 { return &v.Port })`,
		"func (v *Config) DecodeJSON(r *marshal.Reader) error {",
		"return configSchema.Decode(r, v)",
	}
	for _, w := range want {
		if !strings.Contains(src, w) {
			t.Errorf("generated source missing %q\n---\n%s", w, src)
		}
	}
}

