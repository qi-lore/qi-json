// writePkg writes a single Go source file into a temp dir and returns the dir.
func writePkg(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "input.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

