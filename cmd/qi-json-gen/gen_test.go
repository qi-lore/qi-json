func TestGenerateErrors(t *testing.T) {
	cases := []struct {
		name string
		src  string
		typ  string
		want string
	}{
		{
			name: "unknown type",
			src:  "package example\n\ntype A struct{ N int }\n",
			typ:  "B",
			want: "type B not found",
		},
		{
			name: "not a struct",
			src:  "package example\n\ntype A int\n",
			typ:  "A",
			want: "is not a struct",
		},
		{
			name: "embedded field",
			src:  "package example\n\ntype In struct{ N int }\n\ntype A struct{ In }\n",
			typ:  "A",
			want: "embedded field",
		},
		{
			name: "unsupported kind",
			src:  "package example\n\ntype A struct{ C chan int }\n",
			typ:  "A",
			want: "unsupported type",
		},
		{
			name: "pointer struct",
			src:  "package example\n\ntype P struct{ N int }\n\ntype A struct{ P *P }\n",
			typ:  "A",
			want: "unsupported pointer type",
		},
		{
			name: "map key",
			src:  "package example\n\ntype A struct{ M map[int]string }\n",
			typ:  "A",
			want: "map key",
		},
		{
			name: "nested not generated",
			src:  "package example\n\ntype P struct{ N int }\n\ntype A struct{ P P }\n",
			typ:  "A",
			want: "is not generated",
		},
		{
			name: "duplicate member",
			src:  "package example\n\ntype A struct {\n\tX int `json:\"n\"`\n\tY int `json:\"n\"`\n}\n",
			typ:  "A",
			want: "duplicate member name",
		},
		{
			name: "already has DecodeJSON",
			src:  "package example\n\nimport \"qi-json/marshal\"\n\ntype A struct{ N int }\n\nfunc (a *A) DecodeJSON(r *marshal.Reader) error { return nil }\n",
			typ:  "A",
			want: "already declares DecodeJSON",
		},
		{
			name: "already has EncodeJSON",
			src:  "package example\n\nimport \"qi-json/marshal\"\n\ntype A struct{ N int }\n\nfunc (a *A) EncodeJSON(w *marshal.Writer) error { return nil }\n",
			typ:  "A",
			want: "already declares EncodeJSON",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			dir := writePkg(t, tc.src)
			_, err := generate(dir, []string{tc.typ})
			if err == nil {
				t.Fatal("generate error = nil, want an error")
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error = %q, want it to contain %q", err, tc.want)
			}
		})
	}
}

// TestGeneratedFixtureUpToDate is the drift guard: the checked-in fixture must
// equal what the generator produces from its source.
func TestGeneratedFixtureUpToDate(t *testing.T) {
	const dir = "internal/gentest"
	got, err := generate(dir, []string{"Config", "Point", "Nums"})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	path := filepath.Join(dir, defaultOutput)
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run `make generate`)", path, err)
	}
	if string(got) != string(want) {
		t.Errorf("%s is out of date; run `make generate`\n--- generated ---\n%s", path, got)
	}
}

